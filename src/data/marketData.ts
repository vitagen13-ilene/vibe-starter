// Generates high quality realistic candlestick data for any ticker and timeframe
export function generateCandleData(basePrice: number, timeframe: string): Candle[] {
  let count = 40;
  let volatility = basePrice * 0.015;
  let intervalLabel = 'm';

  switch (timeframe) {
    case '1D':
      count = 48; // 30 min intervals
      volatility = basePrice * 0.008;
      intervalLabel = 'm';
      break;
    case '5D':
      count = 60;
      volatility = basePrice * 0.018;
      intervalLabel = 'h';
      break;
    case '1M':
      count = 30; // Daily
      volatility = basePrice * 0.025;
      intervalLabel = 'd';
      break;
    case '6M':
      count = 60;
      volatility = basePrice * 0.04;
      intervalLabel = 'w';
      break;
    case '1Y':
      count = 52;
      volatility = basePrice * 0.06;
      intervalLabel = 'w';
      break;
    default:
      count = 40;
  }

  const candles: Candle[] = [];
  let currentClose = basePrice * (1 - (count * 0.002)); // slightly trending upward

  const now = new Date();

  for (let i = 0; i < count; i++) {
    const change = (Math.random() - 0.47) * volatility;
    const open = Number((currentClose).toFixed(2));
    const close = Number((open + change).toFixed(2));
    const high = Number((Math.max(open, close) + Math.random() * volatility * 0.6).toFixed(2));
    const low = Number((Math.min(open, close) - Math.random() * volatility * 0.6).toFixed(2));
    const volume = Math.floor(Math.random() * 500000 + 150000);

    const pastDate = new Date(now.getTime() - (count - i) * (timeframe === '1D' ? 1800000 : 86400000));
    const time = timeframe === '1D' 
      ? pastDate.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      : pastDate.toLocaleDateString([], { month: 'short', day: 'numeric' });

    candles.push({
      time,
      open,
      high,
      low,
      close,
      volume,
    });

    currentClose = close;
  }

  // Ensure last candle close equals basePrice
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return candles;
}

